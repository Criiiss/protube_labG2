package com.tecnocampus.LS2.protube_back.comments;

import com.tecnocampus.LS2.protube_back.comments.adapter.in.web.CommentResponseDTO;
import com.tecnocampus.LS2.protube_back.comments.application.service.CommentService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

class CommentServiceIntegrationTest {

    private JdbcTemplate jdbc;
    private CommentService service;

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(
                new DriverManagerDataSource(
                        "jdbc:h2:mem:comments;DB_CLOSE_DELAY=-1",
                        "sa",
                        ""
                )
        );

        jdbc.execute("DROP ALL OBJECTS");

        jdbc.execute("""
                CREATE TABLE users (
                    id BIGINT PRIMARY KEY,
                    username VARCHAR(50)
                )
                """);

        jdbc.execute("""
                CREATE TABLE user_profiles (
                    user_id BIGINT PRIMARY KEY,
                    display_name VARCHAR(100),
                    avatar_url VARCHAR(255)
                )
                """);

        jdbc.execute("""
                CREATE TABLE videos (
                    id BIGINT PRIMARY KEY,
                    status VARCHAR(30),
                    visibility VARCHAR(30)
                )
                """);

        jdbc.execute("""
                CREATE TABLE comments (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    video_id BIGINT,
                    author_id BIGINT,
                    parent_id BIGINT,
                    content VARCHAR(2000),
                    like_count BIGINT,
                    created_at TIMESTAMP,
                    updated_at TIMESTAMP
                )
                """);

        jdbc.execute("""
                CREATE TABLE comment_likes (
                    user_id BIGINT,
                    comment_id BIGINT,
                    created_at TIMESTAMP
                )
                """);

        jdbc.update("""
                INSERT INTO users (id, username)
                VALUES
                    (1, 'author'),
                    (2, 'viewer')
                """);

        jdbc.update("""
                INSERT INTO user_profiles (user_id, display_name, avatar_url)
                VALUES
                    (1, 'Author', 'avatar.png'),
                    (2, 'Viewer', 'https://avatar.test/viewer.png')
                """);

        jdbc.update("""
                INSERT INTO videos (id, status, visibility)
                VALUES (10, 'PUBLISHED', 'PUBLIC')
                """);

        service = new CommentService(jdbc);
    }

    @Test
    void createsRootAndReplyComments() {
        CommentResponseDTO root =
                service.createComment(10L, 1L, "  root comment  ", null);

        CommentResponseDTO reply =
                service.createComment(10L, 2L, " reply comment ", root.id());

        assertNotNull(root.id());
        assertEquals("root comment", root.content());
        assertNull(root.parentId());
        assertEquals(1L, root.authorId());
        assertEquals("author", root.username());
        assertEquals("Author", root.displayName());
        assertEquals("/media/avatar.png", root.avatarUrl());

        assertNotNull(reply.id());
        assertEquals("reply comment", reply.content());
        assertEquals(root.id(), reply.parentId());
        assertEquals(2L, reply.authorId());
    }

    @Test
    void getsCommentsAndReturnsLikeState() {
        CommentResponseDTO comment =
                service.createComment(10L, 1L, "hello", null);

        service.likeComment(10L, comment.id(), 2L);

        List<CommentResponseDTO> comments =
                service.getComments(10L, 2L);

        assertEquals(1, comments.size());

        CommentResponseDTO result = comments.getFirst();

        assertEquals(comment.id(), result.id());
        assertEquals("hello", result.content());
        assertEquals(1L, result.likeCount());
        assertTrue(result.likedByCurrentUser());
        assertEquals("/media/avatar.png", result.avatarUrl());
    }

    @Test
    void updatesAndDeletesOwnedComment() {
        CommentResponseDTO comment =
                service.createComment(10L, 1L, "old content", null);

        CommentResponseDTO updated =
                service.updateComment(
                        10L,
                        comment.id(),
                        1L,
                        "  new content  "
                );

        assertEquals("new content", updated.content());

        service.deleteComment(10L, comment.id(), 1L);

        Integer remaining =
                jdbc.queryForObject(
                        "SELECT COUNT(*) FROM comments",
                        Integer.class
                );

        assertEquals(0, remaining);
    }

    @Test
    void likeAndUnlikeAreIdempotent() {
        CommentResponseDTO comment = service.createComment(10L, 1L, "like me", null);
        CommentResponseDTO firstLike = service.likeComment(10L, comment.id(), 2L);
        assertEquals(1L, firstLike.likeCount());
        assertTrue(firstLike.likedByCurrentUser());
        CommentResponseDTO repeatedLike = service.likeComment(10L, comment.id(), 2L);
        assertEquals(1L, repeatedLike.likeCount());
        assertTrue(repeatedLike.likedByCurrentUser());
        CommentResponseDTO unlike = service.unlikeComment(10L, comment.id(), 2L);
        assertEquals(0L, unlike.likeCount());
        assertFalse(unlike.likedByCurrentUser());
        CommentResponseDTO repeatedUnlike = service.unlikeComment(10L, comment.id(), 2L);
        assertEquals(0L, repeatedUnlike.likeCount());
        assertFalse(repeatedUnlike.likedByCurrentUser());
    }
}